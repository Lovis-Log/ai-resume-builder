export const FIRST_PERSON_PRONOUNS = /\b(i|me|my|mine|we|our|ours|us)\b/i;
export const EMAIL_PATTERN = /^[^\s@]+@[^\s@]+\.[^\s@]+$/;
export const NUMBER_PATTERN = /(\d|%|\$|€|£|#)/;

export function firstWord(value: string): string {
  return value.trim().split(/\s+/)[0]?.toLowerCase().replace(/[^a-z-]/g, "") ?? "";
}

export function startsWithActionVerb(value: string): boolean {
  return ACTION_VERBS.has(firstWord(value));
}

export function hasNumber(value: string): boolean {
  return NUMBER_PATTERN.test(value);
}
